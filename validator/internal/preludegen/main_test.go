// The committed prelude_directives.go must be what generate produces from the
// committed prelude, so a prelude change without `go generate ./validator`
// fails here.
func TestPreludeDirectivesAreGenerated(t *testing.T) {
	prelude, err := os.ReadFile(filepath.Join("..", "..", "imported", "prelude.graphql"))
	require.NoError(t, err)
	want, err := generate(
		&ast.Source{Name: "prelude.graphql", Input: string(prelude), BuiltIn: true},
	)
	require.NoError(t, err)

	got, err := os.ReadFile(filepath.Join("..", "..", "prelude_directives.go"))
	require.NoError(t, err)
	require.Equal(t, string(want), string(got),
		"prelude_directives.go is out of date; run go generate ./validator")
}

func TestGenerate(t *testing.T) {
	cases := map[string]struct {
		input string
		want  string
	}{
		"directives are sorted": {
			input: "directive @skip on FIELD\ndirective @defer on FIELD\n",
			want: "// Code generated by validator/internal/preludegen. DO NOT EDIT.\n\n" +
				"package validator\n\n" +
				"// isPreludeDirective reports whether the prelude declares the named directive.\n" +
				"func isPreludeDirective(name string) bool {\n" +
				"\tswitch name {\n" +
				"\tcase \"defer\", \"skip\":\n" +
				"\t\treturn true\n" +
				"\t}\n" +
				"\treturn false\n" +
				"}\n",
		},
		"one directive": {
			input: "directive @skip on FIELD\n",
			want: "// Code generated by validator/internal/preludegen. DO NOT EDIT.\n\n" +
				"package validator\n\n" +
				"// isPreludeDirective reports whether the prelude declares the named directive.\n" +
				"func isPreludeDirective(name string) bool {\n" +
				"\tswitch name {\n" +
				"\tcase \"skip\":\n" +
				"\t\treturn true\n" +
				"\t}\n" +
				"\treturn false\n" +
				"}\n",
		},
		"no directives": {
			input: "scalar Int\n",
			want: "// Code generated by validator/internal/preludegen. DO NOT EDIT.\n\n" +
				"package validator\n\n" +
				"// isPreludeDirective reports whether the prelude declares the named directive.\n" +
				"func isPreludeDirective(name string) bool {\n" +
				"\treturn false\n" +
				"}\n",
		},
	}
	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			got, err := generate(
				&ast.Source{Name: "prelude.graphql", Input: tc.input, BuiltIn: true},
			)
			require.NoError(t, err)
			require.Equal(t, tc.want, string(got))
		})
	}

	t.Run("unparseable prelude", func(t *testing.T) {
		_, err := generate(&ast.Source{Name: "prelude.graphql", Input: "directive"})
		require.Error(t, err)
	})
}

func TestRun(t *testing.T) {
	cases := map[string]struct {
		prelude   string // written to the input file; empty means no input file
		output    string // relative to the temp dir
		wantErr   string // a substring, with {dir} standing for the temp dir
		wantErrIs error
	}{
		"writes the generated file": {
			prelude: "directive @skip on FIELD\n",
			output:  "out.go",
		},
		"missing input": {
			output:    "out.go",
			wantErr:   "{dir}/prelude.graphql",
			wantErrIs: fs.ErrNotExist,
		},
		"input that does not parse": {
			prelude: "directive",
			output:  "out.go",
			wantErr: "{dir}/prelude.graphql:1:10: Expected @, found <EOF>",
		},
		"output directory that does not exist": {
			prelude:   "directive @skip on FIELD\n",
			output:    filepath.Join("missing", "out.go"),
			wantErr:   "{dir}/missing/out.go",
			wantErrIs: fs.ErrNotExist,
		},
	}
	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			dir := t.TempDir()
			input := filepath.Join(dir, "prelude.graphql")
			if tc.prelude != "" {
				require.NoError(t, os.WriteFile(input, []byte(tc.prelude), 0o600))
			}
			output := filepath.Join(dir, tc.output)

			err := run(input, output)
			if tc.wantErr != "" {
				require.ErrorContains(t, err,
					strings.ReplaceAll(filepath.FromSlash(tc.wantErr), "{dir}", dir))
				if tc.wantErrIs != nil {
					require.ErrorIs(t, err, tc.wantErrIs)
				}
				require.NoFileExists(t, output)
				return
			}
			require.NoError(t, err)

			want, err := generate(&ast.Source{Name: input, Input: tc.prelude})
			require.NoError(t, err)
			got, err := os.ReadFile(output)
			require.NoError(t, err)
			require.Equal(t, string(want), string(got))

			// Compare with a file written as 0o644 under the same umask.
			reference := filepath.Join(dir, "reference")
			require.NoError(t, os.WriteFile(reference, nil, 0o644))
			wantInfo, err := os.Stat(reference)
			require.NoError(t, err)
			gotInfo, err := os.Stat(output)
			require.NoError(t, err)
			require.Equal(t, wantInfo.Mode(), gotInfo.Mode())
		})
	}
}
