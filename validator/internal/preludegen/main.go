// Command preludegen writes validator/prelude_directives.go, which reports the
// directives validator/imported/prelude.graphql declares. Run it with
// `go generate ./validator` after changing the prelude.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"slices"
	"strconv"
	"strings"

	"github.com/vektah/gqlparser/v2/ast"
	"github.com/vektah/gqlparser/v2/parser"
)

// main is the untested shell around run: it only supplies the paths and
// reports the error.
//
// mutator-disable-func
func main() {
	if err := run("imported/prelude.graphql", "prelude_directives.go"); err != nil {
		log.Fatal(err)
	}
}

// run writes to outputPath the Go source that generate returns for the prelude
// at inputPath.
func run(inputPath, outputPath string) error {
	input, err := os.ReadFile(inputPath)
	if err != nil {
		return err
	}
	out, err := generate(&ast.Source{Name: inputPath, Input: string(input)})
	if err != nil {
		return err
	}
	return os.WriteFile(outputPath, out, 0o644)
}

// generate returns the Go source of isPreludeDirective for the directives
// prelude declares, sorted by name so the output is stable.
func generate(prelude *ast.Source) ([]byte, error) {
	doc, err := parser.ParseSchema(prelude)
	if err != nil {
		return nil, err
	}
	names := make([]string, len(doc.Directives))
	for i, dir := range doc.Directives {
		names[i] = strconv.Quote(dir.Name)
	}
	slices.Sort(names)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by validator/internal/preludegen. DO NOT EDIT.\n\n")
	buf.WriteString("package validator\n\n")
	buf.WriteString(
		"// isPreludeDirective reports whether the prelude declares the named directive.\n",
	)
	buf.WriteString("func isPreludeDirective(name string) bool {\n")
	if len(names) > 0 {
		fmt.Fprintf(&buf, "\tswitch name {\n\tcase %s:\n\t\treturn true\n\t}\n",
			strings.Join(names, ", "))
	}
	buf.WriteString("\treturn false\n}\n")
	return format.Source(buf.Bytes())
}
